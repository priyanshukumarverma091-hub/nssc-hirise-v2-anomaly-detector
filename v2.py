def v2_reconstruction_loss(y_true, y_pred):

    # Pixel-level reconstruction error
    mse = tf.reduce_mean(
        tf.square(y_true - y_pred),
        axis=[1, 2, 3]
    )

    # Structural similarity
    ssim = tf.image.ssim(
        y_true,
        y_pred,
        max_val=1.0
    )

    # Convert SSIM into structural error
    ssim_loss = 1.0 - ssim

    # Combined loss
    loss = (
        0.7 * mse
        + 0.3 * ssim_loss
    )

    return tf.reduce_mean(loss)

