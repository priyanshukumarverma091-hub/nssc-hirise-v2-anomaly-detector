def load_split(file_list, target_size=(227, 227)):

    arr = np.empty(
        (
            len(file_list),
            target_size[0],
            target_size[1],
            1
        ),
        dtype=np.float32
    )

    for i, fp in enumerate(file_list):

        img = Image.open(fp).convert("L")

        if img.size != target_size:
            img = img.resize(target_size)

        arr[i, :, :, 0] = (
            np.asarray(img, dtype=np.float32) / 255.0
        )

    return arr


