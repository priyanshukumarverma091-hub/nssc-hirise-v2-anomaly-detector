# V2 IMPROVED CNN AUTOENCODER
# ============================================================

def build_v2_autoencoder():

    # --------------------------------------------------------
    # ENCODER
    # --------------------------------------------------------

    encoder_input = keras.Input(
        shape=INPUT_SHAPE,
        name="image_input"
    )

    x = layers.Conv2D(
        32,
        3,
        strides=2,
        padding="same",
        activation="relu",
        name="enc_conv1"
    )(encoder_input)

    x = layers.BatchNormalization(
        name="enc_bn1"
    )(x)

    x = layers.Conv2D(
        64,
        3,
        strides=2,
        padding="same",
        activation="relu",
        name="enc_conv2"
    )(x)

    x = layers.BatchNormalization(
        name="enc_bn2"
    )(x)

    x = layers.Conv2D(
        128,
        3,
        strides=2,
        padding="same",
        activation="relu",
        name="enc_conv3"
    )(x)

    x = layers.BatchNormalization(
        name="enc_bn3"
    )(x)

    x = layers.Conv2D(
        256,
        3,
        strides=2,
        padding="same",
        activation="relu",
        name="enc_conv4"
    )(x)

    x = layers.BatchNormalization(
        name="enc_bn4"
    )(x)

    # Additional feature extraction
    x = layers.Conv2D(
        256,
        3,
        padding="same",
        activation="relu",
        name="enc_conv5"
    )(x)

    x = layers.GlobalAveragePooling2D(
        name="global_pool"
    )(x)

    latent = layers.Dense(
        LATENT_DIM,
        activation=None,
        name="latent_vector"
    )(x)

    encoder = keras.Model(
        encoder_input,
        latent,
        name="V2_Encoder"
    )

    # --------------------------------------------------------
    # DECODER
    # --------------------------------------------------------

    decoder_input = keras.Input(
        shape=(LATENT_DIM,),
        name="latent_input"
    )

    x = layers.Dense(
        15 * 15 * 256,
        activation="relu",
        name="dec_dense"
    )(decoder_input)

    x = layers.Reshape(
        (15, 15, 256),
        name="dec_reshape"
    )(x)

    x = layers.Conv2DTranspose(
        256,
        3,
        strides=2,
        padding="same",
        activation="relu",
        name="dec_deconv1"
    )(x)

    x = layers.BatchNormalization(
        name="dec_bn1"
    )(x)

    x = layers.Conv2DTranspose(
        128,
        3,
        strides=2,
        padding="same",
        activation="relu",
        name="dec_deconv2"
    )(x)

    x = layers.BatchNormalization(
        name="dec_bn2"
    )(x)

    x = layers.Conv2DTranspose(
        64,
        3,
        strides=2,
        padding="same",
        activation="relu",
        name="dec_deconv3"
    )(x)

    x = layers.BatchNormalization(
        name="dec_bn3"
    )(x)

    x = layers.Conv2DTranspose(
        32,
        3,
        strides=2,
        padding="same",
        activation="relu",
        name="dec_deconv4"
    )(x)

    x = layers.BatchNormalization(
        name="dec_bn4"
    )(x)

    x = layers.Resizing(
        227,
        227,
        interpolation="bilinear",
        name="output_resize"
    )(x)

    decoder_output = layers.Conv2D(
        1,
        3,
        padding="same",
        activation="sigmoid",
        name="reconstruction"
    )(x)

    decoder = keras.Model(
        decoder_input,
        decoder_output,
        name="V2_Decoder"
    )

    # --------------------------------------------------------
    # FULL AUTOENCODER
    # --------------------------------------------------------

    autoencoder_input = keras.Input(
        shape=INPUT_SHAPE,
        name="autoencoder_input"
    )

    latent_vector = encoder(
        autoencoder_input
    )

    reconstruction = decoder(
        latent_vector
    )

    autoencoder = keras.Model(
        autoencoder_input,
        reconstruction,
        name="NSSC_HiRISE_V2"
    )

    return encoder, decoder, autoencoder


